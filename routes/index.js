import express from 'express';
import { bookingController as b } from '../controllers/bookingController.js';
import { asyncRoute as a } from '../services/validation.js';
import { accountController as account, requireAccount, requireAdmin } from '../controllers/accountController.js';
import { adminController as admin } from '../controllers/adminController.js';
import { savePreferences } from '../services/preferences.js';
import { hotels } from '../services/hotelCatalog.js';
const router = express.Router();
router.post('/api/preferences', a(savePreferences));
router.get('/sign-in', account.signIn);
router.get('/join', account.join);
router.get('/account', account.page);
router.post('/api/auth/register', a(account.register));
router.post('/api/auth/sign-in', a(account.signInApi));
router.post('/api/auth/sign-out', a(account.signOut));
router.get('/api/account/bookings', requireAccount, a(account.bookings));
router.get('/api/account/notifications', requireAccount, a(account.notifications));
router.post('/api/account/notifications/read', requireAccount, a(account.readNotifications));
