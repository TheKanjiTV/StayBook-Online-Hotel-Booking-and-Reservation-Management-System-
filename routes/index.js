router.get('/admin', requireAdmin, a(admin.dashboard));
router.get('/admin/bookings', requireAdmin, a(admin.list));
router.get('/admin/audit-logs', requireAdmin, a(admin.audit));
router.get('/admin/bookings/:id', requireAdmin, a(admin.detail));
router.get('/admin/bookings/:id/edit', requireAdmin, a(admin.edit));
router.post('/api/admin/bookings/:id/cancel', requireAdmin, a(admin.cancel));
router.post('/api/admin/bookings/:id/confirm', requireAdmin, a(admin.confirm));
router.post('/api/admin/bookings/:id/update', requireAdmin, a(admin.update));
router.post('/api/admin/bookings/:id/delete', requireAdmin, a(admin.delete));
