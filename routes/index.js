import express from 'express';
import { bookingController as b } from '../controllers/bookingController.js';
import { asyncRoute as a } from '../services/validation.js';
const router = express.Router();
router.get('/', b.home);
router.get('/rooms', b.roomsPage);
router.get('/rooms/search', a(b.searchRooms));
router.get('/guest-details', b.guestDetailsPage);
router.post('/booking/preview', a(b.createBookingPreview));
router.get('/confirmation', b.confirmationPage);
router.get('/api/booking-preview', b.getBookingPreview);
router.post('/api/bookings/confirm', a(b.confirmBooking));
router.get('/api/bookings/current', a(b.currentBooking));
router.get('/manage-booking', (req, res) => res.render('manage-booking', { title: 'My booking | StayBook' }));
router.post('/api/bookings/lookup', a(b.lookupBooking));
router.post('/api/bookings/cancel', a(b.cancelBooking));
export default router;
